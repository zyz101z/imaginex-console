// Bakes the lower-48 state outlines into src/states.mjs — the landmass for the OFFLINE
// atlas (the live MapLibre map draws its own). Separate from bake_geometry.mjs so you can
// refresh the map's shape without re-pulling 100+ road corridors from Overpass.
// Run: node tools/bake_states.mjs
import fs from "fs";
import path from "path";

const SRC = "https://raw.githubusercontent.com/PublicaMundi/MappingAPI/master/data/geojson/us-states.json";
const UA = "FreightNation/1.0 (offline atlas bake)";
const CACHE = path.join(new URL("./cache/", import.meta.url).pathname);
const SKIP = new Set(["Alaska", "Hawaii", "Puerto Rico"]); // the game map is the lower 48

// Douglas-Peucker — degrees, so tolerance is coarse-but-fine for a background landmass.
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const sq = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2;
  const segDist = (p, a, b) => {
    let x = a[0], y = a[1], dx = b[0] - x, dy = b[1] - y;
    if (dx || dy) {
      const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
      if (t > 1) { x = b[0]; y = b[1]; } else if (t > 0) { x += dx * t; y += dy * t; }
    }
    return sq(p, [x, y]);
  };
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [lo, hi] = stack.pop();
    let idx = -1, max = tol * tol;
    for (let i = lo + 1; i < hi; i++) {
      const d = segDist(pts[i], pts[lo], pts[hi]);
      if (d > max) { max = d; idx = i; }
    }
    if (idx > 0) { keep[idx] = true; stack.push([lo, idx], [idx, hi]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const file = path.join(CACHE, "us-states.json");
let states;
if (fs.existsSync(file)) {
  states = JSON.parse(fs.readFileSync(file, "utf8"));
  console.log("using cached us-states.json");
} else {
  fs.mkdirSync(CACHE, { recursive: true });
  const res = await fetch(SRC, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  states = await res.json();
  fs.writeFileSync(file, JSON.stringify(states));
  console.log("fetched us-states.json");
}

const OUT = {};
let pts = 0;
for (const f of states.features) {
  const name = f.properties.name;
  if (SKIP.has(name)) continue;
  const g = f.geometry;
  let rings = g.type === "Polygon" ? [g.coordinates[0]] : g.coordinates.map(c => c[0]);
  // ALWAYS keep a state's main ring — boxy states are cheap to describe (Utah is 12 points,
  // DC is 5) and a point-count filter silently deletes them. Extra rings only earn their
  // bytes if they're substantial: Michigan's two peninsulas, Long Island, the Keys.
  rings.sort((a, b) => b.length - a.length);
  rings = [rings[0], ...rings.slice(1).filter(r => r.length >= 12)].slice(0, 4);
  const simple = rings
    .map(r => simplify(r, 0.06).map(p => [Math.round(p[0] * 1e2) / 1e2, Math.round(p[1] * 1e2) / 1e2]))
    .filter(r => r.length >= 3);
  if (!simple.length) continue;
  OUT[name] = simple;
  pts += simple.reduce((s, r) => s + r.length, 0);
}

const out = `// GENERATED by tools/bake_states.mjs — lower-48 state outlines for the offline atlas.
// Boundaries: US Census cartographic data (public domain). Do not hand-edit; re-run the bake.
// STATES[name] = array of rings; each ring is [[lon,lat], ...].
export const STATES = ${JSON.stringify(OUT)};
`;
fs.writeFileSync(new URL("../src/states.mjs", import.meta.url).pathname, out);
console.log(`states.mjs written: ${Object.keys(OUT).length} states, ${pts} points, ${(out.length / 1024).toFixed(1)}KB`);
